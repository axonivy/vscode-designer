package ch.ivyteam.smart.core.mcp;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class IvyWorkspaceSetupTest {

  @TempDir
  Path tempDir;

  @Test
  void preservesReusedWorkspaceAndResetsWhenRequested() throws IOException {
    var templateProject = tempDir.resolve("aitest/ai-dev-tests/ivy-template/purchase");
    Files.createDirectories(templateProject);
    Files.writeString(templateProject.resolve("fixture.txt"), "initial fixture");

    var setup = new IvyWorkspaceSetup(tempDir);
    var workspace = setup.initialize(false);
    var generatedFile = workspace.resolve("purchase/generated.txt");
    Files.writeString(generatedFile, "generated by test");

    setup.initialize(true);
    assertThat(generatedFile).exists();

    setup.initialize(false);
    assertThat(generatedFile).doesNotExist();
    assertThat(workspace.resolve("purchase/fixture.txt")).content().isEqualTo("initial fixture");
  }

  @Test
  void resetsWorkspaceWithOnlySelectedFixtures() throws IOException {
    var purchase = tempDir.resolve("aitest/ai-dev-tests/ivy-template/purchase");
    var employee = tempDir.resolve("aitest/ai-dev-tests/ivy-template/employee-management");
    Files.createDirectories(purchase);
    Files.createDirectories(employee);
    Files.writeString(employee.resolve("fixture.txt"), "employee fixture");

    var setup = new IvyWorkspaceSetup(tempDir);
    var workspace = setup.initialize(false);
    assertThat(workspace.resolve("purchase")).isDirectory();
    assertThat(workspace.resolve("employee-management")).doesNotExist();

    setup.initialize(false, "employee-management");
    assertThat(workspace.resolve("purchase")).doesNotExist();
    assertThat(workspace.resolve("employee-management/fixture.txt")).content().isEqualTo("employee fixture");
  }

  @Test
  void addsMissingSelectedFixturesWithoutOverwritingReusedProjects() throws IOException {
    var purchase = tempDir.resolve("aitest/ai-dev-tests/ivy-template/purchase");
    var employee = tempDir.resolve("aitest/ai-dev-tests/ivy-template/employee-management");
    Files.createDirectories(purchase);
    Files.createDirectories(employee);
    Files.writeString(purchase.resolve("fixture.txt"), "purchase fixture");
    Files.writeString(employee.resolve("fixture.txt"), "employee fixture");

    var setup = new IvyWorkspaceSetup(tempDir);
    var workspace = setup.initialize(true);
    Files.writeString(workspace.resolve("purchase/fixture.txt"), "modified by test");
    var generatedFile = workspace.resolve("purchase/generated.txt");
    Files.writeString(generatedFile, "generated by test");

    setup.initialize(true, "purchase", "employee-management");
    assertThat(workspace.resolve("purchase/fixture.txt")).content().isEqualTo("modified by test");
    assertThat(generatedFile).content().isEqualTo("generated by test");
    assertThat(workspace.resolve("employee-management/fixture.txt")).content().isEqualTo("employee fixture");
  }
}