package ch.ivyteam.smart.core.mcp;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class IvyWorkspaceSetupTest {

  @TempDir
  Path tempDir;

  @Test
  void preservesReusedWorkspaceAndResetsWhenRequested() throws IOException {
    var templateProject = tempDir.resolve("aitest/ai-dev-tests/ivy-template/purchase");
    Files.createDirectories(templateProject);
    Files.writeString(templateProject.resolve("fixture.txt"), "initial fixture");

    var setup = new IvyWorkspaceSetup(tempDir);
    var workspace = setup.initialize(true);
    var generatedFile = workspace.resolve("purchase/generated.txt");
    Files.writeString(generatedFile, "generated by test");

    setup.initialize(false);
    assertThat(generatedFile).exists();

    setup.initialize(true);
    assertThat(generatedFile).doesNotExist();
    assertThat(workspace.resolve("purchase/fixture.txt")).content().isEqualTo("initial fixture");
  }
}